<template>
  <div class="main-view">
    <!-- Header -->
    <header class="app-header">
      <div class="header-left">
        <div class="brand" @click="router.push('/')">MIROFISH</div>
      </div>
      
      <div class="header-center">
        <div class="view-switcher">
          <button 
            v-for="mode in ['graph', 'split', 'workbench']" 
            :key="mode"
            class="switch-btn"
            :class="{ active: viewMode === mode }"
            @click="viewMode = mode"
          >
            {{ { graph: '图谱', split: '双栏', workbench: '工作台' }[mode] }}
          </button>
        </div>
      </div>

      <div class="header-right">
        <TokenDashboard 
          :projectId="projectData?.project_id"
          :simulationId="simulationId" 
          step="step4"
        />
        <div class="workflow-step">
          <span class="step-num">Step 4/5</span>
          <span class="step-name">报告生成</span>
        </div>
        <div class="step-divider"></div>
        <span class="status-indicator" :class="statusClass">
          <span class="dot"></span>
          {{ statusText }}
        </span>

        <PromptSettings initialStage="4 - report_generation"/>
      </div>
    </header>

    <!-- Main Content Area -->
    <main class="content-area">
      <!-- Left Panel: Graph -->
      <div class="panel-wrapper left" :style="leftPanelStyle">
        <GraphPanel 
          :graphData="graphData"
          :loading="graphLoading"
          :currentPhase="4"
          :isSimulating="false"
          @refresh="refreshGraph"
          @toggle-maximize="toggleMaximize('graph')"
        />
      </div>

      <!-- Right Panel: Step4 报告生成 -->
      <div class="panel-wrapper right" :style="rightPanelStyle">
        <Step4Report
          :reportId="currentReportId"
          :simulationId="simulationId"
          :systemLogs="systemLogs"
          @add-log="addLog"
          @update-status="updateStatus"
        />
      </div>
    </main>
  </div>
</template>

<script setup>
import { ref, computed, onMounted, watch } from 'vue'
import { useRoute, useRouter } from 'vue-router'
import GraphPanel from '../components/GraphPanel.vue'
import Step4Report from '../components/Step4Report.vue'
import TokenDashboard from '../components/TokenDashboard.vue'
import PromptSettings from "../components/PromptSettings.vue"
import { getProject, getGraphData } from '../api/graph'
import { getSimulation, getSimulationUsage } from '../api/simulation'
import { getReport } from '../api/report'

const route = useRoute()
const router = useRouter()

// Props
const props = defineProps({
  reportId: String
})

// Layout State - 默认切换到工作台视角
const viewMode = ref('workbench')

// Data State
const currentReportId = ref(route.params.reportId)
const simulationId = ref(null)
const projectData = ref(null)
const graphData = ref(null)
const graphLoading = ref(false)
const systemLogs = ref([])
const currentStatus = ref('processing') // processing | completed | error

// --- Computed Layout Styles ---
const leftPanelStyle = computed(() => {
  if (viewMode.value === 'graph') return { width: '100%', opacity: 1, transform: 'translateX(0)' }
  if (viewMode.value === 'workbench') return { width: '0%', opacity: 0, transform: 'translateX(-20px)' }
  return { width: '50%', opacity: 1, transform: 'translateX(0)' }
})

const rightPanelStyle = computed(() => {
  if (viewMode.value === 'workbench') return { width: '100%', opacity: 1, transform: 'translateX(0)' }
  if (viewMode.value === 'graph') return { width: '0%', opacity: 0, transform: 'translateX(20px)' }
  return { width: '50%', opacity: 1, transform: 'translateX(0)' }
})

// --- Status Computed ---
const statusClass = computed(() => {
  return currentStatus.value
})

const statusText = computed(() => {
  if (currentStatus.value === 'error') return 'Error'
  if (currentStatus.value === 'completed') return 'Completed'
  return 'Generating'
})

// --- Helpers ---
const addLog = (msg) => {
  const time = new Date().toLocaleTimeString('en-US', { hour12: false, hour: '2-digit', minute: '2-digit', second: '2-digit' }) + '.' + new Date().getMilliseconds().toString().padStart(3, '0')
  systemLogs.value.push({ time, msg })
  if (systemLogs.value.length > 200) {
    systemLogs.value.shift()
  }
}

const updateStatus = (status) => {
  currentStatus.value = status
}

// --- Token Usage Statistics ---
const stats = ref({
  prompt_tokens: 0,
  completion_tokens: 0,
  total_tokens: 0,
  call_count: 0
})

// --- Layout Methods ---
const toggleMaximize = (target) => {
  if (viewMode.value === target) {
    viewMode.value = 'split'
  } else {
    viewMode.value = target
  }
}

// --- Data Logic ---
const loadReportData = async () => {
  try {
    // 优先从查询参数中提前捕获 ID，实现即时计费感应
    if (route.query.projectId) {
      projectData.value = { project_id: route.query.projectId }
      addLog(`从参数预加载项目 ID: ${route.query.projectId}`)
    }
    if (route.query.simulationId) {
      simulationId.value = route.query.simulationId
      addLog(`从参数预加载模拟 ID: ${route.query.simulationId}`)
    }

    // 并行获取项目详细信息 (不仅依赖报告结果)
    const pid = route.query.projectId
    if (pid) {
      getProject(pid).then(projRes => {
        if (projRes.success && projRes.data) {
          projectData.value = projRes.data
          if (projRes.data.graph_id) loadGraph(projRes.data.graph_id)
        }
      })
    }

    addLog(`正在拉取报告元数据: ${currentReportId.value}`)
    // 获取 report 信息，即便报 404 也不应阻塞整体呈现
    const reportRes = await getReport(currentReportId.value)
    
    if (reportRes && reportRes.success) {
      simulationId.value = reportRes.data.simulation_id
      
      if (simulationId.value) {
        const simRes = await getSimulation(simulationId.value)
        if (simRes.success && simRes.data) {
          const simData = simRes.data
          if (simData.project_id && !projectData.value?.name) {
            const projRes = await getProject(simData.project_id)
            if (projRes.success && projRes.data) {
              projectData.value = projRes.data
              if (projRes.data.graph_id) loadGraph(projRes.data.graph_id)
            }
          }
        }
      }
    } else {
      // 容杀 404: 如果报告获取不到（生成初期），如果是 404 则仅记录
      addLog(`报告详情暂未就绪 (可能是生成中): ${reportRes.error || '404'}`)
    }
  } catch (err) {
    addLog(`初始化加载异常: ${err.message}`)
  }
}

const loadGraph = async (graphId) => {
  // 【核心拦截点】如果当前状态正在处理/生成中，绝不触碰数据库
  if (currentStatus.value === 'processing' || currentStatus.value === 'generating') {
    addLog('报告正在生成中，暂缓加载知识图谱以避免网络冲突。')
    return
  }

  graphLoading.value = true
  try {
    const res = await getGraphData(graphId)
    if (res.success) {
      graphData.value = res.data
      addLog('图谱数据加载成功')
    }
  } catch (err) {
    addLog(`图谱加载失败: ${err.message}`)
  } finally {
    graphLoading.value = false
  }
}

const refreshGraph = () => {
  if (projectData.value?.graph_id) {
    loadGraph(projectData.value.graph_id)
  }
}

// Watch route params
watch(() => route.params.reportId, (newId) => {
  if (newId && newId !== currentReportId.value) {
    currentReportId.value = newId
    loadReportData()
  }
}, { immediate: true })

onMounted(() => {
  addLog('ReportView 初始化')
  loadReportData()
})
</script>

